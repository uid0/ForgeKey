#!/usr/bin/env bash
# Refresh src/security/forgekey_ca.h with the OMS-internal CA certificate.
#
# Usage:
#     scripts/build/fetch-forgekey-ca.sh                       # uses default OMS host
#     scripts/build/fetch-forgekey-ca.sh user@oms-host         # over SSH
#     CA_PEM_PATH=/path/to/ca.pem scripts/build/fetch-forgekey-ca.sh   # local file
#
# This is the operator CA that signs both device mTLS client certs AND
# firmware-signing leaves. Distinct from oms_ca.h (the LE root used to
# verify the OMS HTTPS server cert).
#
# Two ways to obtain the CA PEM:
#
#   1. Read it directly from a local file (CA_PEM_PATH env var).
#   2. Fetch it via SSH from the OMS host by exec'ing
#      `python manage.py forgekey_ca export-cert` inside the backend
#      container. The first positional arg is the ssh target.
#
# Run this whenever the OMS operator rotates the internal CA. After
# running, rebuild + reflash devices before the back-end deactivates
# the prior CA, OR pre-bake both during the rotation window by
# concatenating the new and old PEMs in the header.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$REPO_ROOT/src/security/forgekey_ca.h"

if [ -n "${CA_PEM_PATH:-}" ]; then
    if [ ! -r "$CA_PEM_PATH" ]; then
        echo "CA_PEM_PATH=$CA_PEM_PATH is not readable" >&2
        exit 1
    fi
    SOURCE="file:$CA_PEM_PATH"
    CA_PEM="$(cat "$CA_PEM_PATH")"
elif [ $# -ge 1 ]; then
    SSH_TARGET="$1"
    SOURCE="ssh:$SSH_TARGET"
    if ! command -v ssh >/dev/null; then
        echo "ssh is required" >&2
        exit 1
    fi
    # Run the export-cert subcommand in the backend container; print PEM.
    CA_PEM="$(ssh "$SSH_TARGET" \
        'cd /home/uid0/openmakersuite && docker compose -f docker-compose.prod.yml exec -T backend python manage.py forgekey_ca export-cert' \
        2>/dev/null)"
else
    cat >&2 <<EOF
usage: $0 <ssh-target>
       CA_PEM_PATH=/path/to/ca.pem $0

Provide either an SSH target running the OMS prod stack, or set
CA_PEM_PATH to a local CA PEM file (e.g. one exported earlier with
\`docker compose exec backend python manage.py forgekey_ca export-cert\`).
EOF
    exit 1
fi

if ! grep -q "BEGIN CERTIFICATE" <<<"$CA_PEM"; then
    echo "Source did not return a PEM certificate." >&2
    echo "First 200 bytes of output:" >&2
    echo "$CA_PEM" | head -c 200 >&2
    echo >&2
    exit 1
fi

{
    echo "#ifndef FORGEKEY_CA_H"
    echo "#define FORGEKEY_CA_H"
    echo
    echo "// Auto-generated by scripts/build/fetch-forgekey-ca.sh."
    echo "// Source: $SOURCE (fetched $(date -u +%Y-%m-%dT%H:%M:%SZ))"
    echo "// Re-run after the OMS operator rotates the internal CA. Until you"
    echo "// reflash, this device falls back to embedded-pubkey firmware"
    echo "// verification and refuses chain-bearing dispatches signed by the"
    echo "// new CA. To survive a rotation window without re-flashing, run"
    echo "// the script twice and concatenate both PEMs here."
    echo
    echo "#ifndef FORGEKEY_INTERNAL_CA_PEM"
    echo "#define FORGEKEY_INTERNAL_CA_PEM \\"
    echo "$CA_PEM" | sed 's/.*/"&\\n" \\/' | sed '$s/ \\$//'
    echo "#endif"
    echo
    echo "extern const char* kForgekeyInternalCaPem;"
    echo
    echo "#endif"
} > "$OUT"

chmod 644 "$OUT"
echo "Wrote $OUT (source: $SOURCE)"
